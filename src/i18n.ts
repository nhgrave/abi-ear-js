export const messages: { pt: Record<MessageKey, string>; en: Record<MessageKey, string> } = { pt, en }

export function t(key: MessageKey, locale: Locale, vars: Record<string, string | number> = {}): string {
  return messages[locale][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`))
}

export function detectLocale(): Locale {
  const lang = typeof navigator !== 'undefined' ? navigator.language : 'en'
  return lang.toLowerCase().startsWith('pt') ? 'pt' : 'en'
}
